//! TypeScript bindings for every type that crosses the Tauri boundary.
//!
//! The files in `apps/desktop/src/api/generated` come from these Rust types.
//! `generated_ts_bindings_are_current` fails when they are stale. Regenerate with
//! `cargo test -p aurdeck export_bindings -- --ignored`.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use aurdeck_core::{RemoveMode, TransactionState};
use aurdeck_review::{Approval, RepoFile};
use ts_rs::{Config, TS};

use crate::installed::{InstalledPackage, InstalledResponse};
use crate::plan::{
    CommandDto, PlanErrorDto, PlanErrorKind, PlanResponse, QueueItemDto, ReviewItem, ReviewState,
};
use crate::review::ReviewBundle;
use crate::search::{PackageSource, PackageSummary, SearchResponse};
use crate::tx::{PromptDto, PromptErrorKind, TxEventDto, TxRecord};

const HEADER: &str = "// This file is generated from the Rust types by ts-rs. Do not edit it.\n// Regenerate with: cargo test -p aurdeck export_bindings -- --ignored\n\n";

fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/api/generated")
}

/// Writes every binding plus `index.ts` into `dir`.
fn export_all(dir: &Path) {
    let cfg = Config::new().with_large_int("number").with_out_dir(dir);
    let mut names: Vec<String> = Vec::new();
    macro_rules! export {
        ($($t:ty),+ $(,)?) => {$(
            <$t as TS>::export_all(&cfg).expect("export binding");
            names.push(<$t as TS>::ident(&cfg));
        )+};
    }
    export!(
        PackageSource,
        PackageSummary,
        SearchResponse,
        InstalledPackage,
        InstalledResponse,
        RemoveMode,
        QueueItemDto,
        PlanErrorKind,
        PlanErrorDto,
        CommandDto,
        ReviewState,
        ReviewItem,
        PlanResponse,
        RepoFile,
        Approval,
        ReviewBundle,
        TransactionState,
        PromptErrorKind,
        PromptDto,
        TxEventDto,
        TxRecord,
    );
    names.sort();
    names.dedup();
    let mut index = String::from(HEADER);
    for n in &names {
        index.push_str(&format!("export type {{ {n} }} from \"./{n}\";\n"));
    }
    // ts-rs writes its own header; replace it so the files say how to regenerate.
    for entry in fs::read_dir(dir).expect("read dir") {
        let path = entry.expect("entry").path();
        let body = fs::read_to_string(&path).expect("read");
        let body: Vec<&str> = body
            .lines()
            .skip_while(|l| l.starts_with("// This file was generated by") || l.is_empty())
            .collect();
        fs::write(&path, format!("{HEADER}{}\n", body.join("\n"))).expect("write");
    }
    fs::write(dir.join("index.ts"), index).expect("write index.ts");
}

fn read_dir_files(dir: &Path) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    if let Ok(rd) = fs::read_dir(dir) {
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            out.insert(name, fs::read_to_string(e.path()).unwrap_or_default());
        }
    }
    out
}

#[test]
fn generated_ts_bindings_are_current() {
    let tmp = tempfile::tempdir().expect("tempdir");
    export_all(tmp.path());
    let fresh = read_dir_files(tmp.path());
    let committed = read_dir_files(&committed_dir());
    let mut stale: Vec<String> = Vec::new();
    for (name, body) in &fresh {
        match committed.get(name) {
            None => stale.push(format!("{name} (missing)")),
            Some(c) if c != body => stale.push(format!("{name} (differs)")),
            Some(_) => {}
        }
    }
    for name in committed.keys().filter(|n| !fresh.contains_key(*n)) {
        stale.push(format!("{name} (no longer generated)"));
    }
    assert!(
        stale.is_empty(),
        "generated TypeScript bindings are stale: {}. Regenerate with: cargo test -p aurdeck export_bindings -- --ignored",
        stale.join(", ")
    );
}

/// Rewrites `apps/desktop/src/api/generated`. Run with `--ignored`.
#[test]
#[ignore = "regenerates the committed bindings"]
fn export_bindings() {
    let dir = committed_dir();
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("create generated dir");
    export_all(&dir);
}
